import { expect, test } from '@playwright/test'
test.beforeEach(async ({ page }) => {
  page.on('dialog', dialog => dialog.accept())
  await page.goto('/?mode=english')
})
async function start(page: import('@playwright/test').Page) {
  await page.getByRole('button', { name: /START GAME/ }).click()
  await page.getByRole('button', { name: /MULAI PERTANDINGAN/ }).click()
}
test('scoring, wrong, steal, undo, reset and reload work on a real browser', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await start(page)
  await page.getByRole('button', { name: 'Buka jawaban 1', exact: true }).click()
  await expect(page.getByTestId('team-score-0').getByText('40', { exact: true })).toBeVisible()
  for (let i = 0; i < 3; i++) await page.getByRole('button', { name: 'WRONG', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Buka jawaban 2', exact: true })).toBeDisabled()
  await page.getByLabel('Tim perebut').selectOption('1')
  await page.getByRole('button', { name: 'STEAL', exact: true }).click()
  await page.getByRole('button', { name: 'Buka jawaban 2', exact: true }).click()
  await expect(page.getByTestId('team-score-1').getByText('30', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Buka jawaban 3', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'SHOW ALL ANSWERS', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'SHOW ALL ANSWERS', exact: true }).click()
  await expect(page.getByTestId('team-score-1').getByText('30', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'UNDO', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: /CONTINUE GAME/ }).click()
  await expect(page.getByTestId('team-score-1').getByText('30', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'UNDO', exact: true }).click()
  await expect(page.getByTestId('team-score-1').getByText('0', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'RESET ROUND', exact: true }).click()
  await expect(page.getByTestId('team-score-0').getByText('0', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Buka jawaban 1', exact: true })).toBeEnabled()
  expect(errors).toEqual([])
})
test('question editor validates content and game data import rejects invalid files', async ({ page }) => {
  await page.getByRole('button', { name: /QUESTION BANK/ }).click()
  await page.getByRole('button', { name: 'Edit soal ch1-01', exact: true }).click()
  await page.getByLabel('Pertanyaan Inggris').fill('Which desserts taste sweet?')
  await page.getByRole('button', { name: 'Simpan soal', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Which desserts taste sweet?' })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /QUESTION BANK/ }).click()
  await expect(page.getByRole('heading', { name: 'Which desserts taste sweet?' })).toBeVisible()
  await page.getByRole('button', { name: 'Kembali', exact: true }).click()
  await page.getByLabel('Impor data permainan').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{"version":1}') })
  await expect(page.getByRole('alert')).toContainText('Impor ditolak')
})
test('all 30 rounds finish with tied ranks, reflection and printable results', async ({ page }) => {
  await start(page)
  for (let i = 0; i < 30; i++) {
    await page.getByRole('button', { name: 'SHOW ALL ANSWERS', exact: true }).click()
    await page.getByRole('button', { name: i === 29 ? 'FINISH GAME' : 'NEXT QUESTION', exact: true }).click()
  }
  await expect(page.getByRole('heading', { name: 'ENGLISH CHAMPION!' })).toBeVisible()
  await expect(page.getByText('JUARA BERSAMA', { exact: false })).toBeVisible()
  await expect(page.getByText('6 ronde utama dimainkan', { exact: false })).toHaveCount(5)
  await expect(page.getByRole('heading', { name: /Let’s reflect together/ })).toBeVisible()
})
test('layout fits viewport and all five team scores remain present', async ({ page }, testInfo) => {
  await expect(page.locator('.home-content')).toHaveCSS('opacity', '1')
  await page.screenshot({ path: `test-results/home-${testInfo.project.name}.png`, fullPage: true })
  await start(page)
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflow).toBe(false)
  for (let i = 0; i < 5; i++) await expect(page.getByTestId(`team-score-${i}`)).toBeVisible()
  await page.getByRole('button', { name: 'Mode proyektor', exact: true }).click()
  await page.getByRole('button', { name: 'Sembunyikan kontrol', exact: true }).click()
  await expect(page.getByRole('button', { name: 'WRONG', exact: true })).toHaveCount(0)
  await page.screenshot({ path: `test-results/game-${testInfo.project.name}.png`, fullPage: true })
})

test('game remains functional without network after assets have loaded', async ({ page, context }) => {
  await start(page)
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Buka jawaban 1', exact: true }).click()
  await expect(page.getByText('Ice cream', { exact: true })).toBeVisible()
  await expect(page.getByTestId('team-score-0').getByText('40', { exact: true })).toBeVisible()
  await context.setOffline(false)
})
