import { act, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import App from './App'
beforeEach(() => { localStorage.clear(); vi.stubGlobal('matchMedia', () => ({ matches: false, addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {} })) })
it('starts a five-team game, reveals once, and restores score after remount', () => {
  const view = render(<App />)
  fireEvent.click(screen.getByRole('button', { name: /START GAME/i }))
  fireEvent.click(screen.getByRole('button', { name: /MULAI PERTANDINGAN/i }))
  fireEvent.click(screen.getByRole('button', { name: 'Buka jawaban 1' }))
  expect(screen.getByText('Ice cream')).toBeInTheDocument()
  expect(screen.getAllByText('40').length).toBeGreaterThan(0)
  view.unmount()
  render(<App />)
  fireEvent.click(screen.getByRole('button', { name: /CONTINUE GAME/i }))
  expect(screen.getByText('Ice cream')).toBeInTheDocument()
})
it('shows a real question editor with thirty questions', () => {
  render(<App />)
  fireEvent.click(screen.getByRole('button', { name: /QUESTION BANK/i }))
  expect(screen.getByText('30 soal')).toBeInTheDocument()
  fireEvent.click(screen.getAllByRole('button', { name: /Edit soal/ })[0])
  expect(screen.getByLabelText('Pertanyaan Inggris')).toHaveValue('What foods taste sweet?')
})

afterEach(() => vi.useRealTimers())
it('keeps a single timer across rounds, pauses, and leaves non-game screens idle', () => {
  vi.useFakeTimers()
  render(<App />)
  fireEvent.click(screen.getByRole('button', { name: /START GAME/i }))
  fireEvent.click(screen.getByRole('button', { name: /MULAI PERTANDINGAN/i }))
  act(() => { vi.advanceTimersByTime(1000) })
  expect(screen.getByRole('button', { name: 'Ulang timer' })).toHaveTextContent('19s')
  fireEvent.click(screen.getByRole('button', { name: 'NEXT QUESTION' }))
  act(() => { vi.advanceTimersByTime(1000) })
  expect(screen.getByRole('button', { name: 'Ulang timer' })).toHaveTextContent('19s')
  fireEvent.click(screen.getByRole('button', { name: 'PAUSE GAME' }))
  act(() => { vi.advanceTimersByTime(5000) })
  expect(screen.getByRole('button', { name: 'Ulang timer' })).toHaveTextContent('19s')
  fireEvent.click(screen.getByRole('button', { name: 'RESUME GAME' }))
  fireEvent.click(screen.getByRole('button', { name: 'Beranda' }))
  act(() => { vi.advanceTimersByTime(5000) })
  fireEvent.click(screen.getByRole('button', { name: /CONTINUE GAME/ }))
  expect(screen.getByRole('button', { name: 'Ulang timer' })).toHaveTextContent('19s')
})
